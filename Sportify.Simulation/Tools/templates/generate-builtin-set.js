// Writes SportfyRevit/SportfyRevit/BuiltIn<Language>Template.cs from an inspection of one of Revit's own templates (TemplateInspector, SPORTIFY_INSPECT_TEMPLATES): the names of what the
// template brings (view templates, filters, schedules, sheets, views), so that "Hide Revit templates" knows what is Revit's and "Show Revit templates" what to copy back.
//
//   node Tools/templates/generate-builtin-set.js German  <BIM_Architektur_und_Ingenieurbau.inspection.json>     "German\BIM_Architektur_und_Ingenieurbau.rte"
//   node Tools/templates/generate-builtin-set.js English <Default-Multi-Discipline_Metric.inspection.json>      "English\Default-Multi-Discipline_Metric.rte"
// (or without arguments: both, from Tools/fixtures/templates)
const fs = require("fs");
const path = require("path");

const str = s => JSON.stringify(String(s));
const list = (name, items, doc) => `${doc ? "        /// <summary>" + doc + "</summary>\n" : ""}        public static readonly string[] ${name} =\n        {\n${items.map(i => "            " + i + ",").join("\n")}\n        };\n`;
const uniq = a => [...new Set(a)];
const repo = path.join(__dirname, "..", "..", "..");

function generate(language, input, relativeTemplatePath) {
  const j = JSON.parse(fs.readFileSync(input, "utf8"));
  const target = path.join(repo, "SportfyRevit", "SportfyRevit", `BuiltIn${language}Template.cs`);
  const viewTemplates = uniq(j.viewTemplates.map(t => str(t.name))).sort();
  const filters = uniq(j.filters.map(f => str(f.name))).sort();
  const schedules = uniq(j.schedules.map(s => str(s.name))).sort();
  const sheets = uniq(j.sheets.map(s => str(s.number))).sort();
  const views = uniq(j.views.map(v => str(v.type + "|" + v.name))).sort();
  const file = relativeTemplatePath.replace(/\\/g, "\\\\");

  const text = `namespace SportfyRevit
{
    /// <summary>
    /// What Revit's ${language} template (Templates\\${relativeTemplatePath}) brings into a project: ${viewTemplates.length} view templates, ${filters.length} filters, ${schedules.length} schedules, ${sheets.length} sheets, ${views.length} views.
    /// GENERATED by Tools/templates/generate-builtin-set.js from TemplateInspector's inspection of the template: do not edit. "Hide Revit templates" removes these from a Sportify project
    /// (only the ones nothing of the user's uses) and "Show Revit templates" copies them back from the template file.
    /// </summary>
    internal static class BuiltIn${language}Template
    {
        /// <summary>Path of the template below Revit's Templates folder.</summary>
        public const string TemplateFile = "${file}";

${list("ViewTemplates", viewTemplates)}
${list("Filters", filters)}
${list("Schedules", schedules)}
${list("SheetNumbers", sheets)}
${list("Views", views, "\"ViewType|Name\" of each view.")}    }
}
`;
  fs.writeFileSync(target, "﻿" + text.replace(/\r?\n/g, "\r\n"), "utf8");
  console.log(`${path.relative(repo, target)}: ${viewTemplates.length} view templates, ${filters.length} filters, ${schedules.length} schedules, ${sheets.length} sheets, ${views.length} views`);
}

const [language, input, template] = process.argv.slice(2);
if (language) generate(language, input, template);
else {
  const fixtures = path.join(repo, "Sportify.Simulation", "Tools", "fixtures", "templates");
  generate("German", path.join(fixtures, "BIM_Architektur_und_Ingenieurbau.inspection.json"), "German\\BIM_Architektur_und_Ingenieurbau.rte");
  generate("English", path.join(fixtures, "Default-Multi-Discipline_Metric.inspection.json"), "English\\Default-Multi-Discipline_Metric.rte");
}
